'use strict';
const fs=require('node:fs');
const path=require('node:path');
const coverage=JSON.parse(fs.readFileSync(path.join(__dirname,'../audit/reference-coverage.json'),'utf8'));
const {assess,requiredTargets}=require('./reference-acceptance.cjs');
const root=path.join(__dirname,'..');
const target=JSON.parse(fs.readFileSync(path.join(root,'audit/official-classic-target.json'),'utf8'));
const facts=JSON.parse(fs.readFileSync(path.join(root,'audit/official-card-facts.json'),'utf8'));
const careers=JSON.parse(fs.readFileSync(path.join(root,'audit/original-target-2026-11-04/careers.json'),'utf8')).careers.careerData;
const result=assess({root,target,coverage,requiredIds:requiredTargets(coverage,facts,careers)});
console.log('Primary target:',target.primary_origin);
console.log('Reference rules with unit evidence:',coverage.rules.filter(r=>r.status==='unit_verified').length);
console.log('Reference runtime screens verified:',coverage.runtime_screens.filter(r=>r.status==='reference_verified').length+'/'+coverage.runtime_screens.length);
console.log('Source/design/implementation/comparison chains verified:',result.reference_verified+'/'+result.required);
for(const b of result.auxiliary)console.log('AUXILIARY:',b.id,'—',b.reason);
for(const b of result.blockers.slice(0,12))console.log('BLOCKED:',b.id,'—',b.reason);
if(result.blockers.length>12)console.log('Other blocked checks:',result.blockers.length-12);
if(!result.passed){console.error('NOT READY FOR ORIGINAL-EQUIVALENCE RELEASE. No download package should be presented as fully equivalent.');process.exitCode=1}else console.log('Release gate passed');
